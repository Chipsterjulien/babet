-- Babet GTK4: generic free-layout building blocks, strict types and lifetimes.
local gui = babet.gui
local function pair(ok, err)
    assert(ok == true and err == nil, tostring(err))
end
local function rejects(fn, fragment)
    local ok, err = pcall(fn)
    assert(not ok and tostring(err):find(fragment, 1, true), tostring(err))
end

rejects(function() gui.fixed() end, "init() first")
assert(gui.init())

local canvas = assert(gui.fixed())
rejects(function() gui.fixed(1) end, "no arguments")
local child = assert(gui.box())
pair(canvas:put(child, 15.5, 20))
rejects(function() canvas:put(child, 3, 4) end, "already has a GTK parent")
rejects(function() canvas:put(assert(gui.label("x")), math.huge, 10) end, "finite")
rejects(function() canvas:put(assert(gui.label("x")), 1e12, 10) end, "out of range")
rejects(function() canvas:move(child, 1 / 0, 20) end, "finite")
pair(canvas:move(child, 30, 50))
pair(child:setSizeRequest(200, -1))
rejects(function() child:setSizeRequest(1.2, 2) end, "integers")
rejects(function() child:setSizeRequest(-2, 10) end, "out of range")
rejects(function() child:setSizeRequest(10, math.huge) end, "integers")
rejects(function() gui.fixed():move(child, 1, 1) end, "does not belong")
rejects(function() canvas:move(gui.label("unknown"), 1, 1) end, "does not belong")

local weak = setmetatable({}, {__mode = "v"})
for i = 1, 25 do
    do
        local note = assert(gui.label("temporary"))
        weak[1] = note
        pair(canvas:put(note, i, i))
        pair(canvas:remove(note))
        pair(note:setText("detached and still alive"))
    end
    collectgarbage("collect")
    collectgarbage("collect")
    assert(weak[1] == nil, "fixed:remove kept detached widget alive")
end
pair(canvas:remove(child))
pair(canvas:put(child, 0, 0))
pair(canvas:clear())
pair(child:setSizeRequest(210, 110))
pair(canvas:put(child, 2, 3))
pair(canvas:clear())

local area = assert(gui.textView {text = "à\nβ", editable = true})
assert(area:getText() == "à\nβ")
pair(area:setEditable(false))
pair(area:setEditable(true))
rejects(function() gui.textView {editable = "yes"} end, "boolean")
rejects(function() gui.textView {text = 52} end, "string")
rejects(function() gui.textView {text = "a\0b"} end, "embedded NUL")
local changed = 0
pair(area:onChanged(function() changed = changed + 1 end))
pair(area:setText("à\nβ"))
assert(changed == 0, "identical text should not notify")
pair(area:setText("nouvelle idée"))
assert(changed == 1 and area:getText() == "nouvelle idée")
pair(area:onChanged(function() changed = changed + 10; area:onChanged(nil) end))
pair(area:setText("suite"))
assert(changed == 11)
pair(area:setText("suite 2"))
assert(changed == 11)
rejects(function() area:onChanged(12) end, "function or nil")

local check = assert(gui.checkButton {label = "faire", active = true})
assert(check:getActive())
local checked = 0
pair(check:onChanged(function() checked = checked + 1; assert(not check:getActive()) end))
pair(check:setActive(false))
assert(checked == 1)
pair(check:setActive(false))
assert(checked == 1)
pair(check:onChanged(nil))
pair(check:setActive(true))
assert(check:getActive() and checked == 1)
pair(check:setText("cocher"))
rejects(function() check:setActive(1) end, "boolean")
rejects(function() gui.checkButton {active = "true"} end, "boolean")

local progress = assert(gui.progressBar())
assert(progress:getFraction() == 0)
pair(progress:setFraction(0.75))
assert(progress:getFraction() == 0.75)
pair(progress:setShowText(true))
pair(progress:setText("75 %"))
rejects(function() progress:setFraction(1.5) end, "0 to 1")
rejects(function() progress:setFraction(0 / 0) end, "finite")
rejects(function() progress:setShowText(1) end, "boolean")

local expander = assert(gui.expander {label = "Détails", expanded = true})
assert(expander:getExpanded())
pair(expander:setExpanded(false))
assert(not expander:getExpanded())
pair(expander:setText("Compléments"))
rejects(function() gui.expander {expanded = 1} end, "boolean")
local inside = assert(gui.label("contenu"))
pair(expander:add(inside))
rejects(function() expander:add(gui.label("second")) end, "expander already has a child")
pair(expander:remove(inside))
pair(inside:setText("réutilisable"))
pair(expander:add(inside))
pair(expander:clear())

local handle = assert(gui.label("⠿"))
pair(handle:onDrag(function() end))
pair(handle:onDrag(nil))
pair(handle:onDrag(function() end))
rejects(function() handle:onDrag(42) end, "function or nil")
rejects(function() gui.window():onDrag(function() end) end, "windows cannot")
rejects(function() gui.button("non-interactive"):onDrag(function() end) end, "non-interactive")
rejects(function() gui.textView():onDrag(function() end) end, "non-interactive")
-- Prevent cycles in every relevant container, including an already parented
-- container that is an ancestor of its would-be new parent.
local a, b, c = assert(gui.box()), assert(gui.box()), assert(gui.box())
pair(a:add(b)); pair(b:add(c))
rejects(function() c:add(a) end, "parent cycle")
local safe = assert(gui.label("still usable"))
pair(c:add(safe))
local outer, inner = assert(gui.box()), assert(gui.fixed())
pair(outer:add(inner))
rejects(function() inner:put(outer, 0, 0) end, "parent cycle")
pair(inner:put(gui.label("safe fixed"), 2, 4))
local exp_parent, exp_child = assert(gui.box()), assert(gui.expander())
pair(exp_parent:add(exp_child))
rejects(function() exp_child:add(exp_parent) end, "parent cycle")
pair(exp_child:add(gui.label("valid")))
-- A collapsed GtkExpander keeps its GTK child unparented. Cycles and double
-- parenting that pass through it must still be refused.
local folded = assert(gui.expander {label = "replié"})
local folded_inner = assert(gui.box())
pair(folded:add(folded_inner))
rejects(function() folded_inner:add(folded) end, "parent cycle")
local folded_canvas = assert(gui.fixed())
pair(folded_inner:add(folded_canvas))
local folded_outer = assert(gui.box())
pair(folded_outer:add(folded))
rejects(function() folded_canvas:put(folded_outer, 0, 0) end, "parent cycle")
pair(folded:setExpanded(true))
pair(folded_canvas:put(gui.label("still usable"), 1, 1))
local folded_single = assert(gui.expander())
local only_child = assert(gui.label("un seul parent"))
pair(folded_single:add(only_child))
local other_box, other_canvas = assert(gui.box()), assert(gui.fixed())
rejects(function() other_box:add(only_child) end, "already has a GTK parent")
rejects(function() other_canvas:put(only_child, 0, 0) end, "already has a GTK parent")
pair(folded_single:setExpanded(true))
pair(folded_single:setExpanded(false))
pair(folded_single:remove(only_child))
pair(other_box:add(only_child))
pair(other_box:remove(only_child))
pair(folded_single:add(only_child))
pair(folded_single:clear())
pair(other_canvas:put(only_child, 2, 2))
-- Reuse between open expanders, collapsed expanders and plain containers.
local open_exp = assert(gui.expander {label = "ouvert", expanded = true})
local roaming = assert(gui.label("itinérant"))
pair(open_exp:add(roaming))
rejects(function() other_box:add(roaming) end, "already has a GTK parent")
pair(open_exp:remove(roaming))
pair(other_box:add(roaming))
pair(other_box:remove(roaming))
pair(open_exp:add(roaming))
pair(open_exp:setExpanded(false))
pair(open_exp:remove(roaming))
pair(folded_single:add(roaming))
pair(folded_single:setExpanded(true))
pair(folded_single:remove(roaming))
pair(open_exp:add(roaming))
pair(open_exp:setExpanded(true))
pair(open_exp:clear())
pair(roaming:setText("toujours vivant"))

-- Callback may destroy its own widget/parent without use-after-free.
local window = assert(gui.window())
local close_check = assert(gui.checkButton())
pair(window:add(close_check))
pair(close_check:onChanged(function() pair(window:close()) end))
pair(close_check:setActive(true))
rejects(function() close_check:getActive() end, "already been destroyed")

print("GUI_FREE_LAYOUT_CONTRACT_OK")
